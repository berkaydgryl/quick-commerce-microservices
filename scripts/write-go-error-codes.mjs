// apps/gateway/internal/apperror/codes_gen.go dosyasini uretir.
//
// NEDEN URETILIYOR: kod -> HTTP eslemesi TEK tablodadir (@getir/core/error-codes.ts)
// ve kullaniciya gosterilecek mesaj TEK sozluktedir (@getir/contracts/errors.ts). Go
// ile yazilan gateway ikisini de import edemez. Elle kopyalansaydi, core'a eklenen yeni
// bir kod gateway'de ya hic taninmaz ya da yanlis HTTP koduyla donerdi ve bunu hicbir
// derleyici yakalamazdi. Uretilen dosya DEPOYA GIRER (Go tarafi Node olmadan
// derlenebilsin diye); guncel olup olmadigini "--check" denetler.
//
// NEDEN KOK scripts/ ALTINDA (D5): betik apps/gateway'e yazar. packages/* hicbir
// apps/*'i tanimaz (proje kurali); iki tarafi bilen tek yer depo kokudur. Paketleri
// kokun devDependencies'inden okur (@getir/core, @getir/contracts).
//
// Kullanim (paketler derlendikten sonra - paketlerin dist'inden okur):
//   node scripts/write-go-error-codes.mjs          -> yazar       (pnpm codes:go)
//   node scripts/write-go-error-codes.mjs --check  -> fark varsa 1 (pnpm codes:go:check)
//
// CIKTI gofmt'a DOKUNULMADAN uyar: tablo tek satirlik struct literal'lerden,
// sabitler ayri bildirimlerden olusur; gofmt'un hizalama yaptigi yapilar
// (const blogu, anahtar: deger satirlari) bilerek kullanilmiyor. Boylece Go kurulu
// olmayan makinede de uretilen dosya CI'daki gofmt kapisindan gecer.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { ERROR_MESSAGES } from '@getir/contracts';
import { ERROR_CODES, httpStatusFor } from '@getir/core';

/** Uretilen dosya; depo kokune gore. */
export const OUTPUT_PATH = fileURLToPath(
  new URL('../apps/gateway/internal/apperror/codes_gen.go', import.meta.url),
);

/**
 * "VALIDATION_FAILED" -> "CodeValidationFailed"
 * @param {string} code
 * @returns {string}
 */
export function goConstName(code) {
  const pascal = code
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
  return `Code${pascal}`;
}

/**
 * Go metin sabiti. JSON kacis kurallari (\", \\, \n, \uXXXX) Go ile uyumludur;
 * Turkce karakterler oldugu gibi kalir (Go kaynagi UTF-8'dir).
 * @param {string} value
 * @returns {string}
 */
function goString(value) {
  return JSON.stringify(value);
}

/**
 * codes_gen.go'nun olmasi gereken icerigi.
 * @returns {string}
 */
export function render() {
  // Sira core'daki bildirim sirasidir; deterministik cikti icin yeterli.
  const codes = Object.values(ERROR_CODES);

  const constants = codes
    .map(
      (code) =>
        `// ${goConstName(code)} = ${code}.\nconst ${goConstName(code)} Code = ${goString(code)}\n`,
    )
    .join('\n');

  const rows = codes
    .map(
      (code) =>
        `\t{code: ${goConstName(code)}, httpStatus: ${httpStatusFor(code)}, message: ${goString(ERROR_MESSAGES[code])}},`,
    )
    .join('\n');

  return `// Code generated by scripts/write-go-error-codes.mjs. DO NOT EDIT.
//
// Kaynak: @getir/core/error-codes.ts (kod -> HTTP) ve @getir/contracts/errors.ts
// (kod -> kullanici mesaji). Degistirmek icin kaynagi duzenleyip "pnpm codes:go"
// calistirin; CI "pnpm codes:go:check" ile farki yakalar.

package apperror

${constants}
// codeTable, her kodun HTTP karsiligi ve kullanici mesaji.
var codeTable = []codeEntry{
${rows}
}
`;
}

/** @returns {string | undefined} */
function readCurrent() {
  try {
    return readFileSync(OUTPUT_PATH, 'utf8');
  } catch {
    return undefined;
  }
}

/**
 * @param {readonly string[]} args
 * @returns {number} cikis kodu
 */
function main(args) {
  const expected = render();
  if (args.includes('--check')) {
    if (readCurrent() !== expected) {
      console.error(
        'apps/gateway/internal/apperror/codes_gen.go guncel degil. "pnpm codes:go" calistirip commit edin.',
      );
      return 1;
    }
    console.log('codes_gen.go guncel.');
    return 0;
  }
  writeFileSync(OUTPUT_PATH, expected);
  console.log(`yazildi: ${OUTPUT_PATH}`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
